async fn accept_downstream(
    stream: TcpStream,
    cli_token: &str,
) -> Result<WebSocketStream<TcpStream>, String> {
    let cli_token = cli_token.to_string();
    // tungstenite's `Callback` trait dictates this exact `Result<Response,
    // ErrorResponse>` signature; `ErrorResponse` (`http::Response<Option<String>>`)
    // is not something this closure can shrink or box.
    #[allow(clippy::result_large_err)]
    let callback = move |request: &Request, response: Response| {
        let authorized = request
            .headers()
            .get("authorization")
            .and_then(|value| value.to_str().ok())
            .and_then(|value| value.strip_prefix("Bearer "))
            .map(|token| constant_time_eq(token, &cli_token))
            .unwrap_or(false);
        if authorized {
            Ok(response)
        } else {
            let error_response = tokio_tungstenite::tungstenite::http::Response::builder()
                .status(StatusCode::UNAUTHORIZED)
                .body(Some("Unauthorized".to_string()))
                .expect("static 401 response is well-formed");
            Err(error_response)
        }
    };
    accept_hdr_async(stream, callback)
        .await
        .map_err(|error| error.to_string())
}

async fn connect_upstream(
    app_server_url: &str,
    app_server_token: &str,
) -> Result<WebSocketStream<tokio_tungstenite::MaybeTlsStream<TcpStream>>, String> {
    let mut upstream_request = app_server_url
        .into_client_request()
        .map_err(|error| format!("failed to build upstream request: {error}"))?;
    let header_value = format!("Bearer {app_server_token}")
        .parse()
        .map_err(|error| format!("invalid App Server authorization header: {error}"))?;
    upstream_request
        .headers_mut()
        .insert("authorization", header_value);
    match time::timeout(UPSTREAM_CONNECT_TIMEOUT, connect_async(upstream_request)).await {
        Ok(Ok((socket, _response))) => Ok(socket),
        Ok(Err(error)) => Err(error.to_string()),
        Err(_) => Err("timed out".to_string()),
    }
}

async fn bridge_session<Upstream>(
    downstream: WebSocketStream<TcpStream>,
    upstream: WebSocketStream<Upstream>,
    state: SharedState,
) -> &'static str
where
    Upstream: tokio::io::AsyncRead + tokio::io::AsyncWrite + Unpin + Send + 'static,
{
    let (mut downstream_write, mut downstream_read) = downstream.split();
    let (upstream_write, mut upstream_read) = upstream.split();

    let (upstream_tx, mut upstream_rx) = mpsc::unbounded_channel::<Message>();
    let mut writer_task = tokio::spawn(async move {
        let mut upstream_write = upstream_write;
        while let Some(message) = upstream_rx.recv().await {
            if upstream_write.send(message).await.is_err() {
                break;
            }
        }
    });

    let mut shutdown_rx = state.shutdown_tx.subscribe();
    let reason: &'static str = loop {
        tokio::select! {
            changed = shutdown_rx.changed() => {
                if changed.is_err() || *shutdown_rx.borrow() {
                    let _ = upstream_tx.send(Message::Close(None));
                    let _ = downstream_write.send(Message::Close(None)).await;
                    break "shutdown";
                }
            }
            message = downstream_read.next() => {
                let Some(Ok(message)) = message else {
                    let _ = upstream_tx.send(Message::Close(None));
                    break "cli";
                };
                if let Some((metadata, text)) = log_frame(&state, CLI_TO_APP, &message) {
                    annotate_cli_response(&state, &metadata, &text);
                }
                let is_close = message.is_close();
                if upstream_tx.send(message).is_err() || is_close {
                    break "cli";
                }
            }
            message = upstream_read.next() => {
                let Some(Ok(message)) = message else {
                    let _ = downstream_write.send(Message::Close(None)).await;
                    break "app_server";
                };
                let is_close = message.is_close();
                let forward = handle_app_to_cli(&state, &message, &upstream_tx);
                if forward && downstream_write.send(message).await.is_err() {
                    break "app_server";
                }
                if is_close {
                    break "app_server";
                }
            }
        }
    };

    drop(upstream_tx);
    if time::timeout(WRITER_DRAIN_TIMEOUT, &mut writer_task)
        .await
        .is_err()
    {
        writer_task.abort();
    }
    reason
}

/// Logs a frame in full and returns its classified metadata plus raw text
/// when it was a text (JSON-RPC) message.
fn log_frame(
    state: &SharedState,
    direction: &str,
    message: &Message,
) -> Option<(JsonRpcMetadata, String)> {
    match message {
        Message::Text(text) => {
            let text = text.as_str().to_string();
            let metadata = classify_json_rpc(&text);
            let header = format!(
                "{direction} kind={:?} method={} id={}",
                metadata.kind,
                metadata.method.as_deref().unwrap_or("-"),
                metadata
                    .id
                    .as_ref()
                    .map(ToString::to_string)
                    .unwrap_or_else(|| "-".to_string())
            );
            state.logger.block(&header, &pretty_json_text(&text));
            Some((metadata, text))
        }
        Message::Binary(data) => {
            state
                .logger
                .line(&format!("{direction} kind=binary bytes={}", data.len()));
            None
        }
        Message::Ping(_) => {
            state.logger.line(&format!("{direction} kind=ping"));
            None
        }
        Message::Pong(_) => {
            state.logger.line(&format!("{direction} kind=pong"));
            None
        }
        Message::Close(frame) => {
            state
                .logger
                .line(&format!("{direction} kind=close frame={frame:?}"));
            None
        }
        Message::Frame(_) => {
            state.logger.line(&format!(
                "{direction} kind=raw-frame (unexpected outside read())"
            ));
            None
        }
    }
}

fn pretty_json_text(text: &str) -> String {
    match serde_json::from_str::<Value>(text) {
        Ok(value) => serde_json::to_string_pretty(&value).unwrap_or_else(|_| text.to_string()),
        Err(error) => format!("<non-JSON body, parse error: {error}>\n{text}"),
    }
}

fn pretty_value(value: &Value) -> String {
    serde_json::to_string_pretty(value).unwrap_or_else(|_| value.to_string())
}

/// Handles a frame flowing App Server -> CLI. Returns whether it should
/// still be forwarded down to the CLI.
fn handle_app_to_cli(
    state: &SharedState,
    message: &Message,
    upstream_tx: &mpsc::UnboundedSender<Message>,
) -> bool {
    let Some((metadata, text)) = log_frame(state, APP_TO_CLI, message) else {
        return true;
    };
    annotate_generic(state, APP_TO_CLI, &metadata);

    if metadata.kind != JsonRpcKind::Request
        || metadata.method.as_deref() != Some(REQUEST_APPROVAL_METHOD)
    {
        return true;
    }

    let Ok(full) = serde_json::from_str::<Value>(&text) else {
        state
            .logger
            .line("ERROR failed to parse requestApproval frame as JSON despite classification succeeding; passthrough");
        return true;
    };
    let Some(id) = full.get("id").cloned() else {
        state
            .logger
            .line("ERROR requestApproval frame has no id; cannot intervene, passthrough");
        return true;
    };
    let params = full.get("params").cloned().unwrap_or(Value::Null);
    log_request_approval_params(&state.logger, &params);

    let occurrence = state.approvals_detected.fetch_add(1, Ordering::SeqCst) + 1;
    state.logger.line(&format!(
        "requestApproval #{occurrence}/{} detected (id={id})",
        state.max_approvals
    ));

    let id_key = id.to_string();
    let turn_id = params
        .get("turnId")
        .and_then(Value::as_str)
        .map(str::to_string);
    let available: Vec<Value> = params
        .get("availableDecisions")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();

    let mut tracked = TrackedApproval::new(id.clone(), turn_id, state.logger.elapsed_ms());

    let forward_to_cli = match state.mode {
        Mode::Observe => {
            tracked.note = "observe: passthrough, no intervention".to_string();
            true
        }
        Mode::HoldForever => {
            tracked.note =
                "hold-forever: swallowed, never forwarded, no response scheduled".to_string();
            state.logger.line(
                "INTERVENE hold-forever: withholding requestApproval from CLI permanently \
                 (no response will ever be sent; watching for an App Server-side timeout)",
            );
            false
        }
        Mode::Race | Mode::Hold => {
            if available.is_empty() {
                state.logger.line(
                    "NOTE availableDecisions is empty/absent; cannot fabricate a response, \
                     passthrough without intervention",
                );
                tracked.note = "no availableDecisions offered; passthrough".to_string();
                true
            } else {
                match select_decision(&available, state.decision_arg.as_deref()) {
                    Ok(decision) => {
                        let decision = decision.clone();
                        tracked.decision = Some(decision.clone());
                        let forward = state.mode == Mode::Race;
                        if forward {
                            state.logger.line(&format!(
                                "INTERVENE race: forwarding requestApproval to CLI as usual, AND \
                                 scheduling a probe response with decision {} in {:?}",
                                decision_label(&decision),
                                state.delay
                            ));
                            tracked.note =
                                "race: forwarded to CLI + probe response scheduled".to_string();
                        } else {
                            state.logger.line(&format!(
                                "INTERVENE hold: withholding requestApproval from CLI, scheduling a \
                                 probe response with decision {} in {:?}",
                                decision_label(&decision),
                                state.delay
                            ));
                            tracked.note =
                                "hold: withheld from CLI + probe response scheduled".to_string();
                        }
                        schedule_probe_response(
                            state,
                            upstream_tx,
                            id.clone(),
                            id_key.clone(),
                            decision,
                        );
                        forward
                    }
                    Err(message) => {
                        state
                            .logger
                            .line(&format!("ERROR decision selection failed: {message}"));
                        tracked.note =
                            format!("decision mismatch ({message}); passthrough, no intervention");
                        true
                    }
                }
            }
        }
    };

    state
        .tracked
        .lock()
        .unwrap()
        .insert(id_key.clone(), tracked);
    schedule_settlement_watch(state, id_key);
    forward_to_cli
}

fn log_request_approval_params(logger: &Logger, params: &Value) {
    let command = params
        .get("command")
        .and_then(Value::as_str)
        .unwrap_or("<none>");
    let cwd = params
        .get("cwd")
        .and_then(Value::as_str)
        .unwrap_or("<none>");
    let reason = params
        .get("reason")
        .and_then(Value::as_str)
        .unwrap_or("<none>");
    let kind = params
        .get("kind")
        .and_then(Value::as_str)
        .unwrap_or("command");
    logger.line(&format!(
        "requestApproval fields: command={command:?} cwd={cwd:?} reason={reason:?} kind={kind:?}"
    ));
    let available = params
        .get("availableDecisions")
        .cloned()
        .unwrap_or(Value::Null);
    logger.block(
        "requestApproval availableDecisions",
        &pretty_value(&available),
    );
    logger.block("requestApproval params (full)", &pretty_value(params));
}

fn schedule_probe_response(
    state: &SharedState,
    upstream_tx: &mpsc::UnboundedSender<Message>,
    id: Value,
    id_key: String,
    decision: Value,
) {
    let state = state.clone();
    let upstream_tx = upstream_tx.clone();
    let delay = state.delay;
    tokio::spawn(async move {
        time::sleep(delay).await;
        let response = json!({
            "jsonrpc": "2.0",
            "id": id,
            "result": { "decision": decision },
        });
        let text = serde_json::to_string(&response).unwrap_or_default();
        state.logger.block(
            &format!("{PROBE_TO_APP} sending fabricated response for id={id}"),
            &pretty_json_text(&text),
        );
        if let Ok(mut tracked) = state.tracked.lock() {
            if let Some(entry) = tracked.get_mut(&id_key) {
                entry.probe_response_sent = true;
                entry.probe_response_at_ms = Some(state.logger.elapsed_ms());
            }
        }
        if upstream_tx.send(Message::text(text)).is_err() {
            state
                .logger
                .line("ERROR failed to send fabricated response upstream (channel closed)");
        }
    });
}

fn annotate_cli_response(state: &SharedState, metadata: &JsonRpcMetadata, text: &str) {
    if metadata.kind != JsonRpcKind::Response {
        return;
    }
    let Some(id) = metadata.id.as_ref() else {
        return;
    };
    let id_key = id.to_string();
    let body = serde_json::from_str::<Value>(text)
        .ok()
        .and_then(|full| full.get("result").or_else(|| full.get("error")).cloned());
    let mut tracked = state.tracked.lock().unwrap();
    if let Some(entry) = tracked.get_mut(&id_key) {
        entry.cli_response_seen = true;
        entry.cli_response_at_ms = Some(state.logger.elapsed_ms());
        entry.cli_response_body = body;
        let note = if entry.probe_response_sent {
            format!(
                "[correlate] this is the CLI's OWN response to requestApproval id={id}, arriving \
                 AFTER the probe already answered at +{}ms -- a duplicate submission to the App Server",
                entry.probe_response_at_ms.unwrap_or_default()
            )
        } else {
            format!(
                "[correlate] this is the CLI's own response to requestApproval id={id} (no probe \
                 response was sent for this id)"
            )
        };
        drop(tracked);
        state.logger.line(&note);
    }
}

fn annotate_generic(state: &SharedState, direction: &str, metadata: &JsonRpcMetadata) {
    let mut tracked = state.tracked.lock().unwrap();
    if tracked.is_empty() {
        return;
    }
    if metadata.method.as_deref() == Some("turn/completed") {
        if let Some(turn_id) = &metadata.turn_id {
            for entry in tracked.values_mut() {
                if entry.turn_id.as_deref() == Some(turn_id.as_str()) && !entry.turn_completed {
                    entry.turn_completed = true;
                    entry.turn_completed_at_ms = Some(state.logger.elapsed_ms());
                    entry.turn_status = metadata.turn_status.clone();
                    let id = entry.id.clone();
                    let status = entry.turn_status.clone();
                    drop(tracked);
                    state.logger.line(&format!(
                        "[correlate] {direction} turn/completed for turnId={turn_id} (approval \
                         id={id}, turn.status={})",
                        status.as_deref().unwrap_or("-")
                    ));
                    return;
                }
            }
        }
    } else if metadata.method.as_deref() == Some("serverRequest/resolved") {
        if let Some(request_id) = &metadata.request_id {
            let key = request_id.to_string();
            if let Some(entry) = tracked.get_mut(&key) {
                entry.resolved_notification_seen = true;
                entry.resolved_notification_at_ms = Some(state.logger.elapsed_ms());
                drop(tracked);
                state.logger.line(&format!(
                    "[correlate] {direction} serverRequest/resolved for id={request_id}"
                ));
            }
        }
    } else if metadata.response_is_error {
        if let Some(id) = &metadata.id {
            let key = id.to_string();
            if let Some(entry) = tracked.get_mut(&key) {
                entry.error_response_seen = true;
                entry.error_response_at_ms = Some(state.logger.elapsed_ms());
                drop(tracked);
                state.logger.line(&format!(
                    "[correlate] {direction} JSON-RPC error response for id={id}"
                ));
            }
        }
    }
}

/// Watches one requestApproval occurrence until it settles or the observe
/// window runs out, instead of ending the run on a fixed post-detection
/// timer.
///
/// This replaces an earlier design (`schedule_drain_shutdown`) that slept a
/// FIXED `--delay-seconds + 2s` after detecting the requestApproval and then
/// shut everything down. On a real device run with `--mode observe` (no
/// intervention at all, so the fixed timer was the only thing driving
/// shutdown), the probe exited about 7 seconds after the request appeared --
/// BEFORE the human at the keyboard had answered the CLI's prompt. That
/// timer was measuring the wrong thing: what `hold`/`race` actually need to
/// observe is what happens AFTER an answer is sent -- `serverRequest/resolved`,
/// the approved command actually running, `turn/completed`, and (for `race`)
/// a late/duplicate response from the CLI arriving at some unpredictable
/// human-paced time. A fixed timer anchored to detection has no way to know
/// any of that has happened yet, so it cuts the log off exactly where the
/// interesting part starts. Instead, this polls the tracked state for the
/// occurrence and only finalizes it once a response (the probe's own or the
/// CLI's) AND `turn/completed` have both been observed and stayed observed
/// for `SETTLE_TAIL` (nothing else about it is still in flight), or once
/// `--observe-seconds` has elapsed since detection with no such luck --
/// whichever happens first, so a configuration that never sends
/// `turn/completed` (or never gets answered at all, as in `hold-forever`)
/// still terminates in bounded time.
fn schedule_settlement_watch(state: &SharedState, id_key: String) {
    let state = state.clone();
    tokio::spawn(async move {
        let deadline = Instant::now() + state.observe_seconds;
        let mut settled_since: Option<Instant> = None;
        loop {
            let now = Instant::now();
            let (responded, turn_done, response_at_ms, turn_at_ms) = {
                let tracked = state.tracked.lock().unwrap();
                match tracked.get(&id_key) {
                    Some(entry) => (
                        entry.probe_response_sent || entry.cli_response_seen,
                        entry.turn_completed,
                        entry.probe_response_at_ms.or(entry.cli_response_at_ms),
                        entry.turn_completed_at_ms,
                    ),
                    None => (false, false, None, None),
                }
            };

            if responded && turn_done {
                let since = *settled_since.get_or_insert(now);
                if now.saturating_duration_since(since) >= SETTLE_TAIL {
                    finalize_occurrence(
                        &state,
                        &id_key,
                        SettlementOutcome::Settled,
                        format!(
                            "settled (response observed at +{}ms, turn/completed at +{}ms, \
                             tail {}s elapsed)",
                            response_at_ms.unwrap_or_default(),
                            turn_at_ms.unwrap_or_default(),
                            SETTLE_TAIL.as_secs()
                        ),
                    );
                    return;
                }
            } else {
                settled_since = None;
            }

            if now >= deadline {
                finalize_occurrence(
                    &state,
                    &id_key,
                    SettlementOutcome::TimedOut,
                    format!(
                        "observe window elapsed (--observe-seconds {}) — the approval may not \
                         have been resolved",
                        state.observe_seconds.as_secs()
                    ),
                );
                return;
            }

            let remaining = deadline.saturating_duration_since(now);
            time::sleep(
                SETTLE_POLL_INTERVAL
                    .min(remaining)
                    .max(Duration::from_millis(1)),
            )
            .await;
        }
    });
}

/// Marks one occurrence's observation window as finished, and -- once
/// `max_approvals` occurrences have each finished this way -- ends the run.
fn finalize_occurrence(
    state: &SharedState,
    id_key: &str,
    outcome: SettlementOutcome,
    reason_detail: String,
) {
    let already_finalized = {
        let mut tracked = state.tracked.lock().unwrap();
        match tracked.get_mut(id_key) {
            Some(entry) if entry.outcome.is_none() => {
                entry.outcome = Some(outcome);
                entry.outcome_at_ms = Some(state.logger.elapsed_ms());
                false
            }
            _ => true,
        }
    };
    if already_finalized {
        return;
    }
    state
        .logger
        .line(&format!("requestApproval id={id_key} {reason_detail}"));

    let processed = state.approvals_processed.fetch_add(1, Ordering::SeqCst) + 1;
    if processed >= state.max_approvals
        && !state.final_shutdown_triggered.swap(true, Ordering::SeqCst)
    {
        state
            .logger
            .line(&format!("shutdown reason: {reason_detail}"));
        if outcome == SettlementOutcome::TimedOut {
            state
                .final_shutdown_is_timeout
                .store(true, Ordering::SeqCst);
        }
        let _ = state.shutdown_tx.send(true);
    }
}

fn select_decision<'a>(
    available: &'a [Value],
    requested: Option<&str>,
) -> Result<&'a Value, String> {
    match requested {
        None => available
            .first()
            .ok_or_else(|| "availableDecisions is empty".to_string()),
        Some(name) => available
            .iter()
            .find(|candidate| decision_matches(candidate, name))
            .ok_or_else(|| {
                let choices: Vec<String> = available.iter().map(decision_label).collect();
                format!(
                    "requested decision {name:?} not found; available: [{}]",
                    choices.join(", ")
                )
            }),
    }
}

fn decision_matches(value: &Value, name: &str) -> bool {
    match value {
        Value::String(candidate) => candidate == name,
        Value::Object(map) if map.len() == 1 => map.keys().next().is_some_and(|key| key == name),
        _ => false,
    }
}

fn decision_label(value: &Value) -> String {
    match value {
        Value::String(candidate) => candidate.clone(),
        Value::Object(map) if map.len() == 1 => map
            .keys()
            .next()
            .cloned()
            .unwrap_or_else(|| "?".to_string()),
        other => other.to_string(),
    }
}

fn print_summary(
    logger: &Logger,
    tracked: &StdMutex<HashMap<String, TrackedApproval>>,
    timed_out: bool,
) {
    let tracked = tracked.lock().unwrap();
    logger.line(&format!(
        "=== SUMMARY: {} requestApproval occurrence(s) observed ===",
        tracked.len()
    ));
    let mut entries: Vec<&TrackedApproval> = tracked.values().collect();
    entries.sort_by_key(|entry| entry.detected_at_ms);
    for entry in entries {
        let header = format!("id={} (received at +{}ms)", entry.id, entry.detected_at_ms);
        let outcome = match entry.outcome {
            Some(SettlementOutcome::Settled) => "settled",
            Some(SettlementOutcome::TimedOut) => "observe-window-timeout",
            None => "unresolved (run ended before this occurrence's watch finished)",
        };
        let body = format!(
            "note: {}\n\
             observation outcome: {}{}\n\
             probe response: sent={} decision={}{}\n\
             CLI response: seen={}{} body={}\n\
             duplicate (both probe and CLI answered this id): {}\n\
             serverRequest/resolved observed: {}{}\n\
             turn/completed observed: {} turn.status={}{}\n\
             JSON-RPC error response observed for this id: {}{}",
            entry.note,
            outcome,
            optional_ms(entry.outcome_at_ms),
            entry.probe_response_sent,
            entry
                .decision
                .as_ref()
                .map(decision_label)
                .unwrap_or_else(|| "-".to_string()),
            optional_ms(entry.probe_response_at_ms),
            entry.cli_response_seen,
            optional_ms(entry.cli_response_at_ms),
            entry
                .cli_response_body
                .as_ref()
                .map(ToString::to_string)
                .unwrap_or_else(|| "-".to_string()),
            entry.probe_response_sent && entry.cli_response_seen,
            entry.resolved_notification_seen,
            optional_ms(entry.resolved_notification_at_ms),
            entry.turn_completed,
            entry.turn_status.as_deref().unwrap_or("-"),
            optional_ms(entry.turn_completed_at_ms),
            entry.error_response_seen,
            optional_ms(entry.error_response_at_ms),
        );
        logger.block(&header, &body);
    }
    if timed_out {
        logger
            .line("WARNING: exited on the observe-window timeout; the aftermath may be incomplete");
    }
    logger.line("=== END SUMMARY ===");
}

fn optional_ms(value: Option<u128>) -> String {
    match value {
        Some(ms) => format!(" (+{ms}ms)"),
        None => String::new(),
    }
}

struct Logger {
    file: StdMutex<File>,
    start: Instant,
}

impl Logger {
    fn create(path: &Path) -> Result<Self, String> {
        let file = OpenOptions::new()
            .create(true)
            .append(true)
            .open(path)
            .map_err(|error| format!("failed to create log file {}: {error}", path.display()))?;
        Ok(Self {
            file: StdMutex::new(file),
            start: Instant::now(),
        })
    }

    fn elapsed_ms(&self) -> u128 {
        self.start.elapsed().as_millis()
    }

    fn emit(&self, ms: u128, text: &str) {
        let stamped = format!("[+{ms:>8}ms] {text}");
        println!("{stamped}");
        if let Ok(mut file) = self.file.lock() {
            let _ = writeln!(file, "{stamped}");
            let _ = file.flush();
        }
    }

    fn line(&self, text: &str) {
        self.emit(self.elapsed_ms(), text);
    }

    /// Logs a header line followed by every line of `body`, all indented and
    /// stamped with the same elapsed time so a multi-line frame stays
    /// visually grouped and time-ordered.
    fn block(&self, header: &str, body: &str) {
        let ms = self.elapsed_ms();
        self.emit(ms, header);
        for line in body.lines() {
            self.emit(ms, &format!("    {line}"));
        }
    }

    /// Writes text verbatim, with no timestamp prefix, to both the console
    /// and the log file. Used only for the copy-pasteable CLI launch
    /// instructions, which must not be corrupted by a log prefix.
    fn raw(&self, text: &str) {
        println!("{text}");
        if let Ok(mut file) = self.file.lock() {
            let _ = writeln!(file, "{text}");
            let _ = file.flush();
        }
    }
}

struct ChildKillGuard(Option<Child>);

impl ChildKillGuard {
    fn new(child: Child) -> Self {
        Self(Some(child))
    }

    fn as_mut(&mut self) -> &mut Child {
        self.0.as_mut().expect("child guard used after release")
    }

    fn into_inner(mut self) -> Child {
        self.0.take().expect("child guard used after release")
    }
}

impl Drop for ChildKillGuard {
    fn drop(&mut self) {
        if let Some(mut child) = self.0.take() {
            let _ = child.start_kill();
        }
    }
}

async fn wait_for_port(
    child: &mut Child,
    port: u16,
    timeout: Duration,
    logger: &Logger,
) -> Result<(), String> {
    let deadline = Instant::now() + timeout;
    loop {
        if let Some(exit) = child
            .try_wait()
            .map_err(|error| format!("failed to poll Codex App Server: {error}"))?
        {
            return Err(format!("Codex App Server exited before listening: {exit}"));
        }
        if TcpStream::connect(("127.0.0.1", port)).await.is_ok() {
            logger.line(&format!(
                "Codex App Server is listening on 127.0.0.1:{port}"
            ));
            return Ok(());
        }
        if Instant::now() >= deadline {
            return Err(format!(
                "timed out waiting for Codex App Server to listen on 127.0.0.1:{port}"
            ));
        }
        time::sleep(Duration::from_millis(150)).await;
    }
}

async fn pick_free_port() -> Result<u16, String> {
    let listener = TcpListener::bind("127.0.0.1:0")
        .await
        .map_err(|error| format!("failed to allocate a free port: {error}"))?;
    listener
        .local_addr()
        .map(|addr: SocketAddr| addr.port())
        .map_err(|error| format!("failed to read allocated port: {error}"))
}

fn random_token() -> Result<String, String> {
    let mut bytes = [0_u8; 32];
    getrandom::fill(&mut bytes).map_err(|error| format!("failed to generate token: {error}"))?;
    Ok(hex::encode(bytes))
}

fn constant_time_eq(left: &str, right: &str) -> bool {
    left.as_bytes().ct_eq(right.as_bytes()).into()
}

fn absolute_path(path: &Path) -> Result<PathBuf, String> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        env::current_dir()
            .map(|cwd| cwd.join(path))
            .map_err(|error| format!("failed to resolve path {}: {error}", path.display()))
    }
}

/// Minimal Ctrl+C detection via a raw `SetConsoleCtrlHandler` binding.
///
/// `tokio`'s `signal` feature is not enabled for this workspace and adding
/// it (or the `windows` crate's `Win32_System_Console` feature) would be a
/// new dependency footprint, which this probe must avoid. `kernel32` is
/// always linked on Windows targets, so this needs no extra crate.
#[cfg(windows)]
mod ctrlc {
    use std::sync::atomic::AtomicBool;

    pub static SHUTDOWN_REQUESTED: AtomicBool = AtomicBool::new(false);

    const CTRL_C_EVENT: u32 = 0;
    const CTRL_BREAK_EVENT: u32 = 1;
    const CTRL_CLOSE_EVENT: u32 = 2;

    #[link(name = "kernel32")]
    extern "system" {
        fn SetConsoleCtrlHandler(
            handler_routine: Option<unsafe extern "system" fn(u32) -> i32>,
            add: i32,
        ) -> i32;
    }

    unsafe extern "system" fn handler(ctrl_type: u32) -> i32 {
        match ctrl_type {
            CTRL_C_EVENT | CTRL_BREAK_EVENT | CTRL_CLOSE_EVENT => {
                SHUTDOWN_REQUESTED.store(true, std::sync::atomic::Ordering::SeqCst);
                1
            }
            _ => 0,
        }
    }

    pub fn install() {
        // Safety: `handler` matches the expected `PHANDLER_ROUTINE` signature
        // and is valid for the lifetime of the process (it is a plain `fn`,
        // never unregistered).
        unsafe {
            let _ = SetConsoleCtrlHandler(Some(handler), 1);
        }
    }
}

#[cfg(not(windows))]
mod ctrlc {
    use std::sync::atomic::AtomicBool;

    pub static SHUTDOWN_REQUESTED: AtomicBool = AtomicBool::new(false);

    pub fn install() {}
}

#[cfg(windows)]
fn hide_child_window(command: &mut Command) {
    use std::os::windows::process::CommandExt;
    const CREATE_NO_WINDOW: u32 = 0x0800_0000;
    command.as_std_mut().creation_flags(CREATE_NO_WINDOW);
}


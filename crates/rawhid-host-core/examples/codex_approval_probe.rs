//! Manual probe for observing how the Codex CLI's TUI and the Codex App
//! Server react when a `item/commandExecution/requestApproval` request is
//! answered by something other than the real CLI.
//!
//! This mirrors `claude_hook_probe.rs` in spirit (CLI argument handling, log
//! formatting, and process-lifecycle conventions) but targets the Codex
//! Broker's WebSocket JSON-RPC relay (`crates/rawhid-host-core/src/codex_broker.rs`)
//! instead of Claude Code's HTTP hooks.
//!
//! Topology:
//!
//! ```text
//! [Codex CLI]  --WS-->  [this probe: intercepting relay]  --WS-->  [codex app-server]
//!    started by a human in a separate terminal      spawned by this program
//! ```
//!
//! The probe spawns `codex app-server`, listens for the CLI's WebSocket
//! connection itself (printing a copy-pasteable launch command for a human
//! to run in another terminal — the CLI is a TUI and must never be started
//! by this probe), and relays every frame between the two sides while
//! logging it in full. When it detects a `requestApproval` request flowing
//! from the App Server to the CLI, it can additionally answer that request
//! itself (impersonating the CLI), either alongside the CLI's real answer
//! (`race`, answering question Q-A: does a duplicate response confuse
//! anything?) or instead of forwarding the request to the CLI at all
//! (`hold`, answering question Q-B: can the Broker resolve approvals without
//! the CLI ever seeing them?). `hold-forever` withholds the request and
//! never answers it, to probe the App Server's own timeout behavior.
//!
//! Response shape and `availableDecisions` were confirmed against the actual
//! schema generated by `codex app-server generate-json-schema --experimental`
//! (see `CommandExecutionRequestApprovalResponse.json` /
//! `CommandExecutionRequestApprovalParams.json`), not assumed from design
//! docs. The response is exactly `{"decision": <one element of
//! availableDecisions, treated as opaque JSON>}`.

